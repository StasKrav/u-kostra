// ============================================================
// УТИЛИТЫ
// ============================================================
function pickRandom(arr) { return arr[Math.floor(Math.random() * arr.length)]; }
function randInt(min, max) { return Math.floor(Math.random() * (max - min + 1)) + min; }

// ============================================================
// ОЧИСТКА
// ============================================================
function clean() {
  console.log('🧹 Удаляю сгенерированные данные...');
  // Удаляем только тех пользователей, у которых token начинается с "seed_"
  const seedUsers = db.prepare("SELECT id FROM users WHERE token LIKE 'seed_%'").all();
  const ids = seedUsers.map(u => u.id);

  if (ids.length === 0) {
    console.log('   Нечего удалять.');
    return;
  }

  const placeholders = ids.map(() => '?').join(',');
  db.prepare(`DELETE FROM messages WHERE user_id IN (${placeholders})`).run(...ids);
  db.prepare(`DELETE FROM presence WHERE user_id IN (${placeholders})`).run(...ids);
  db.prepare(`DELETE FROM votes WHERE user_id IN (${placeholders})`).run(...ids);
  db.prepare(`DELETE FROM users WHERE id IN (${placeholders})`).run(...ids);

  console.log(`   Удалено пользователей: ${ids.length}`);
}

// ============================================================
// СИДИНГ
// ============================================================
function seed() {
  console.log('🔥 Генерирую данные для теста...\n');

  // 1. Пользователи
  const createUser = db.prepare(`
    INSERT INTO users (token, display_name, name_locked, last_seen)
    VALUES (?, ?, 1, unixepoch() - ?)
  `);

  const userIds = [];
  const usedNames = new Set();

  for (let i = 0; i < USERS_COUNT; i++) {
    // Уникальный ник
    let name;
    let attempts = 0;
    do {
      name = pickRandom(NAMES);
      if (usedNames.has(name)) name = name + ' ' + pickRandom(['II', 'III', 'мл.', 'ст.']);
      attempts++;
    } while (usedNames.has(name) && attempts < 20);
    usedNames.add(name);

    const token = 'seed_' + randomBytes(8).toString('hex');
    const lastSeenAgo = randInt(60, 3600 * 24); // от минуты до суток назад
    const info = createUser.run(token, name, lastSeenAgo);
    userIds.push({ id: info.lastInsertRowid, name });
  }

  console.log(`👥 Создано пользователей: ${userIds.length}`);

  // 2. Реплики
  const glades = queries.listGlades.all();
  const insertMsg = db.prepare(`
    INSERT INTO messages (glade_id, user_id, display_name, text, kind, created_at, score)
    VALUES (?, ?, ?, ?, 'normal', ?, ?)
  `);

  const now = Math.floor(Date.now() / 1000);
  const spanSeconds = DAYS_SPAN * 24 * 3600;

  // Распределяем реплики по полянам примерно равномерно
  const perGlade = Math.floor(TOTAL_MESSAGES / glades.length);
  let totalInserted = 0;

  for (const glade of glades) {
    const lines = LINES[glade.slug] || LINES.common;
    let count = perGlade;

    // Последней поляне — остаток
    if (glade === glades[glades.length - 1]) {
      count = TOTAL_MESSAGES - totalInserted;
    }

    for (let i = 0; i < count; i++) {
      const user = pickRandom(userIds);
      const text = pickRandom(lines);
      const createdAt = now - randInt(0, spanSeconds);

      // Score: большинство — 0..3, некоторые — отрицательные, редкие — сильно положительные
      const r = Math.random();
      let score;
      if (r < 0.05) score = randInt(-5, -2);      // 5% — утопленные
      else if (r < 0.15) score = randInt(4, 12);   // 10% — популярные
      else score = randInt(0, 3);                  // 85% — обычные

      insertMsg.run(glade.id, user.id, user.name, text, createdAt, score);
      totalInserted++;
    }
  }

  console.log(`💬 Создано реплик: ${totalInserted}`);
  console.log(`   Распределено по ${glades.length} полянам (~${perGlade} на каждую)`);

  // 3. Presence — посадим людей на каждую поляну
  const insertPresence = db.prepare(`
    INSERT INTO presence (user_id, glade_id, joined_at, last_seen)
    VALUES (?, ?, unixepoch() - ?, unixepoch())
    ON CONFLICT(user_id, glade_id) DO NOTHING
  `);

  let presenceCount = 0;
  for (const glade of glades) {
    const shuffled = [...userIds].sort(() => Math.random() - 0.5);
    const chosen = shuffled.slice(0, PRESENCE_PER_GLADE);
    for (const u of chosen) {
      insertPresence.run(u.id, glade.id, randInt(60, 3600));
      presenceCount++;
    }
  }

  console.log(`👀 Посажено «сидеть»: ${presenceCount} (${PRESENCE_PER_GLADE} на поляну)`);

  console.log('\n✅ Готово. Обнови страницу в браузере.');
  console.log('   Чтобы очистить: node scripts/seed.js --clean\n');
}

// ============================================================
// ЗАПУСК
// ============================================================
const args = process.argv.slice(2);
if (args.includes('--clean')) {
  clean();
} else {
  seed();
}
